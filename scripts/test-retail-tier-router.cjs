const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),cp=require('node:child_process');
for(const script of ['retail-cart.js','retail-checkout.js','inquiry.js'])
 cp.execFileSync(process.execPath,['--check','public/'+script]);
const cartSource=fs.readFileSync('public/retail-cart.js','utf8');
const checkout=fs.readFileSync('public/retail-checkout.html','utf8');
const checkoutJs=fs.readFileSync('public/retail-checkout.js','utf8');
const cartHtml=fs.readFileSync('public/retail-cart.html','utf8');
const inquiry=fs.readFileSync('public/inquiry.js','utf8');
assert.equal((cartSource.match(/function redraw\(/g)||[]).length,1,'Cart JS must not be duplicated');
assert.equal((cartSource.match(/const money=/g)||[]).length,1,'Cart JS must have exactly one money formatter');
assert(cartSource.includes('quantity()>=10'));
assert(cartSource.includes("cart_flow:'wholesale'"));
assert(cartSource.includes("sea_accepted:'yes'"));
assert(cartSource.includes("retail-checkout.html"));
assert(cartSource.includes("'cartWholesale').hidden=!bulk"));
assert(cartHtml.includes('id="bulkSeaConsent"'));
assert(cartHtml.includes('25–30 days after dispatch'));
assert(cartHtml.includes('Quantity-based')||cartSource.includes('Quantity discount'));
assert(cartHtml.includes('id="cartShippingTitle"'));
assert(cartHtml.includes('id="cartSummaryHeading"'));
assert(checkout.includes('noindex,nofollow'));
assert(checkout.includes('id="retailCheckoutForm" hidden'));
assert(checkout.includes('id="retailTurnstile"'));
assert(checkout.includes('id="retailShippingConsent"'));
assert(checkout.includes('id="retailTaxConsent"'));
assert(checkoutJs.includes("mingeagle_checkout"));
assert(checkoutJs.includes("retailCheckoutReady"));
assert(checkoutJs.includes("d.paymentStatus==='PAID'"));
assert(checkoutJs.includes("AirwallexComponentsSDK"));
assert(!checkoutJs.includes('creditCardNumber'),'We never store card numbers');
assert(inquiry.includes("Wholesale volume-discount request (NOT PAID)"));
assert(inquiry.includes("wholesaleSeaAgreement"));
assert(inquiry.includes('seaCheck.required=active'));
assert(inquiry.includes('25–30 days after dispatch'));
const db=new Map();
const memory={getItem:k=>db.get(k)||null,setItem:(k,v)=>db.set(k,v),removeItem:k=>db.delete(k)};
const context={window:{},localStorage:memory,document:{getElementById:()=>null},console};
vm.runInNewContext(cartSource,context);
const cart=context.window.MingEagleCart;
assert(cart&&typeof cart.add==='function');
assert.equal(cart.add('P1-S3',1),1);
assert.equal(cart.add('P2-S5',8),9);
assert.equal(cart.add('P3-S7',1),10);
assert.equal(cart.read().reduce((n,x)=>n+x.quantity,0),10);
assert.equal(cart.add('__proto__',1),0,'SKU injection fails closed');
assert.equal(cart.add('P1-S4',1),0,'Unlisted variant fails closed');
assert.equal(cart.add('P1-S3',10001),0,'Unreasonable quantity fails closed');
console.log('PASS: valid retail cart JS; 9/10 boundary, no invented wholesale discounts, explicit sea consent, guarded Airwallex checkout and webhook-only order success.');
